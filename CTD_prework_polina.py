# The program checks a job seeker's eligibility for a job
# by asking about their years of experience
# and whether they possess at least a Bachelor's degree

years_of_exp = int(input("How many years of experience in Instructional Design do you have?"))

print(years_of_exp, "year(s)")

if int(years_of_exp) >= 5:
  print("You have enough experience to be qualified for this job")
else:
  print("You do not have enough experience to be qualified for this job")

degree_req = input("Do you possess at least a Bachelor's degree?")

if degree_req == "yes":
  print("You meet the educational qualifications for this position")
else:
  print("You do not meet the educational qualifications for this position")

if int(years_of_exp) >= 5 and degree_req == "yes":
  print("You are eligible for this job!")
else:
  print ("You are not eligible for this job.")

print ("Years of experience:", years_of_exp, "Degree requirement:", degree_req)


